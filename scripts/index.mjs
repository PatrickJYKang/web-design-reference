#!/usr/bin/env node
// Rebuild design-references/INDEX.md from the frontmatter of every entry in refs/.

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LIB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../design-references');
const REQUIRED = ['url', 'captured', 'type', 'summary'];

function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i < 0) continue;
    let v = line.slice(i + 1).trim();
    if (v.startsWith('[') && v.endsWith(']')) v = v.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean);
    else v = v.replace(/^["']|["']$/g, '');
    out[line.slice(0, i).trim()] = v;
  }
  return out;
}

const files = (await fs.readdir(path.join(LIB, 'refs')).catch(() => [])).filter((f) => f.endsWith('.md')).sort();
const TYPES = ['landing', 'pricing', 'docs', 'editorial', 'portfolio', 'commerce', 'app'];
const byType = new Map();
let bad = 0;
let cards = 0;
for (const f of files) {
  const text = await fs.readFile(path.join(LIB, 'refs', f), 'utf8');
  const fm = frontmatter(text);
  const missing = fm ? REQUIRED.filter((k) => !fm[k] || String(fm[k]).includes('TODO')) : REQUIRED;
  // A draft that nobody has finished stays out of the index.
  const problem = missing.length ? `missing ${missing.join(', ')}` : !TYPES.includes(fm.type) ? `type "${fm.type}" is not one of ${TYPES.join(', ')}` : /^- TODO$/m.test(text) ? 'unfinished (TODO lines)' : null;
  if (problem) {
    bad++;
    console.error(`refs/${f}: ${problem}`);
    continue;
  }
  const tags = Array.isArray(fm.tags) ? fm.tags.join(', ') : fm.tags || '';
  const card = fm.depth === 'card';
  if (card) cards++;
  if (!byType.has(fm.type)) byType.set(fm.type, []);
  byType.get(fm.type).push(`- \`${f.slice(0, -3)}\` · ${fm.sector || '-'} · ${tags} — ${fm.summary}${card ? ' (card)' : ''}`);
}
const total = [...byType.values()].reduce((a, l) => a + l.length, 0);

const body = [
  '# Index',
  '',
  'One line per entry in `refs/`, grouped by page type: slug · sector · tags — character. `(card)` marks a short entry: measured values and a brief reading, without component recipes. Generated by `npm run index`; edit the entries, not this file.',
  '',
  ...(total ? TYPES.filter((t) => byType.has(t)).flatMap((t) => [`## ${t} (${byType.get(t).length})`, '', ...byType.get(t).sort(), '']) : ['_No entries yet._', '']),
].join('\n');
await fs.writeFile(path.join(LIB, 'INDEX.md'), body);
console.log(`INDEX.md: ${total} entr${total === 1 ? 'y' : 'ies'} (${cards} cards)${bad ? `, ${bad} skipped` : ''}`);
process.exit(bad ? 1 : 0);
